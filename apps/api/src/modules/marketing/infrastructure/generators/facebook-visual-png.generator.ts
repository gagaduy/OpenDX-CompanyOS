import type { VisualAsset } from "../../domain/entities/marketing-campaign";

// Valid 1080x1080 1:1 RGBA PNG buffer header & empty pixel data
const DEFAULT_1080_PNG = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x04, 0x38, 0x00, 0x00, 0x04, 0x38,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x9b, 0x6e, 0x76,
  0xee, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41,
  0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
  0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00,
  0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae,
  0x42, 0x60, 0x82,
]);

export function generateFacebookVisualPng(
  visualAsset: VisualAsset,
  existingBuffer?: Buffer,
): {
  buffer: Buffer;
  filename: string;
  mediaType: "image/png";
} {
  const buffer = existingBuffer && existingBuffer.length >= 8 ? existingBuffer : DEFAULT_1080_PNG;

  return {
    buffer,
    filename: `facebook_visual_${visualAsset.campaignId}.png`,
    mediaType: "image/png",
  };
}
